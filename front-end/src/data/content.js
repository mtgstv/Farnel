// Data "dd/mm/aaaa" a N dias de hoje (negativo = no passado). As doações de exemplo
// usam datas relativas ao dia em que são carregadas, para não vencerem todas com o tempo.
function diasAPartirDeHoje(dias) {
    const data = new Date();
    data.setDate(data.getDate() + dias);
    return data.toLocaleDateString("pt-BR");
}

